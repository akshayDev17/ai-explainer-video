// The Go adapter and its rule packs: each pack's fixture mined and diffed against its golden links, plus the
// resolution rules the adapter exists for (packages through go.mod, receivers, interfaces by method set, factory
// narrowing, promoted methods, closures, goroutines and callbacks) and go test evidence.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { join, dirname } from 'node:path';
import { writeFileSync, mkdirSync } from 'node:fs';
import { FIXTURES, mine, ruleView, assertGolden, edgesFrom, short, gitRepo, cleanup } from './helpers.mjs';

const pack = name => {
  const r = mine(join(FIXTURES, 'rules', name));
  assert.equal(r.status, 0, r.stderr);
  return r.codemap;
};
const testsView = m => m.tests.map(t => `${t.id} asserts ${t.assertLines.join(',')} | mocked ${t.mocked.join(',')} | direct ${t.direct.map(d => `${d.to}/${d.via}`).join(',')}`
  + (t.subtests ? ` | subtests ${t.subtests.join(',')}` : '') + (t.table ? ` | table ${t.table.over}:${t.table.cases}` : ''));

test('go-http: net/http, gin, echo and chi routes with their prefixes, mounts and middleware', () => {
  const m = pack('go-http');
  assertGolden('go-http', ruleView(m));
  const routes = m.entries.filter(e => e.kind === 'http').map(e => `${e.method} ${e.path} ${short(e.id)}`).sort();
  assert.ok(routes.includes('GET /v1/stats stats'), 'StripPrefix mounts a sub-mux under its prefix');
  assert.ok(routes.includes('GET /api/orders/{path} orderFiles'), 'a router handed to a function carries its group prefix; gin *path is {path}');
  assert.ok(routes.includes('GET /accounts/{id} getAccount'), 'chi Route(prefix, func(r)) and {id:[0-9]+}');
  assert.ok(routes.includes('GET /admin/stats adminStats'), 'chi Mount of a router a function returns');
  assert.ok(routes.includes('* /files/{path} fileServer.ServeHTTP'), 'a handler value is its ServeHTTP method');
  assert.equal(m.edges.some(e => e.rule === 'go.callback' && e.from === 'nethttp/server.go:NewMux'), false, 'a registered handler is the router\'s to run');
  assert.equal(m.edges.some(e => e.rule === 'go.callback' && e.to === 'chiapp/router.go:audit'), false, 'chi With() middleware too');
});

test('grpc: a registered server\'s methods are rpc entries at their HTTP/2 paths; generated and external clients cross to them', () => {
  const m = pack('grpc');
  assertGolden('grpc', ruleView(m));
  assert.equal(m.entries.some(e => e.path === '/greet.Greeter/Farewell'), false, 'a method only the Unimplemented stub serves is not served');
  const narrowed = edgesFrom(m, 'client/main.go:main').find(e => e.to === 'greetpb/greet_grpc.pb.go:greeterClient.SayHello');
  assert.equal(narrowed.narrowedBy, 'greetpb/greet_grpc.pb.go:NewGreeterClient', 'the client interface narrows to what NewGreeterClient returns');
});

test('go-test: tests, table tests and subtests, TestMain as a hook, testify and fake doubles standing in for production interfaces', () => {
  const m = pack('go-test');
  assertGolden('go-test', { ...ruleView(m), tests: testsView(m), mocks: m.mocks.map(x => `${x.fn} ${x.how} ${x.raw} -> ${x.target}`).sort() });
  assert.equal(m.tests.some(t => t.id.endsWith('testHelperNotATest')), false, 'only TestXxx with *testing.T is a test');
  assert.equal(m.fixtures[0].name, 'TestMain');
});

test('go resolver: packages through go.mod, a /vN package by its own name, receivers, fields, interfaces, narrowing, promotion, closures', () => {
  const m = mine(join(FIXTURES, 'go-resolver')).codemap;
  assert.equal(m.selfCheck.ok, true);
  const run = edgesFrom(m, 'svc/svc.go:Service.Run').map(e => `${short(e.to)} ${e.kind}${e.narrowedBy ? ' narrowed' : ''}${e.goroutine ? ' go' : ''}${e.deferred ? ' defer' : ''}${e.rule ? ` ${e.rule}` : ''}`);
  for (const want of ['Base.Log static', 'Store.Get static', 'memStore.Get virtual', 'sqlStore.Get virtual', 'memStore.Get dispatch narrowed', 'sqlStore.Get dispatch narrowed',
    'Item.Price static', 'Service.Run.<locals>.helper static', 'Service.background static go', 'cleanup static defer', 'Service.less static go.callback', 'Format static'])
    assert.ok(run.includes(want), `${want} in ${run.join(', ')}`);
  assert.deepEqual(m.classes.find(k => k.id === 'store/store.go:memStore').bases, ['store/store.go:Store'], 'a type implements an interface by its method set');
  assert.equal(m.selfCheck.go.unresolvedByOrigin.inRepo, 0);
});

test('go: a MockGen-generated file is a test double wherever it lives; --lang go mines only Go', () => {
  const repo = gitRepo();
  mkdirSync(join(repo, 'mocks'));
  writeFileSync(join(repo, 'go.mod'), 'module example.com/m\n');
  writeFileSync(join(repo, 'mocks', 'store.go'), '// Code generated by MockGen. DO NOT EDIT.\npackage mocks\n\ntype MockStore struct{}\n\nfunc (m *MockStore) Get() {}\n');
  writeFileSync(join(repo, 'main.go'), 'package main\n\nfunc main() {}\n');
  writeFileSync(join(repo, 'tool.py'), 'def f():\n    pass\n');
  const m = mine(repo, '--lang', 'go').codemap;
  assert.deepEqual(m.files.find(f => f.path === 'mocks/store.go').group, 'test');
  assert.deepEqual(m.entries.map(e => `${e.kind} ${e.id}`), ['main main.go:main']);
  assert.equal(m.symbols.some(s => s.file === 'tool.py'), false);
  cleanup(dirname(repo));
});

test('go: a type implements an interface only with as many parameters and results per method, none of a clashing type', () => {
  const repo = gitRepo();
  writeFileSync(join(repo, 'go.mod'), 'module example.com/m\n');
  writeFileSync(join(repo, 'store.go'), ['package m', 'type Item struct{}', 'type Store interface{ Get(id string) Item }',
    'type mem struct{}', 'func (m *mem) Get(id string) Item { return Item{} }',
    'type bytesCache struct{}', 'func (c *bytesCache) Get(key int) []byte { return nil }',
    'type pairCache struct{}', 'func (c *pairCache) Get(id string, n int) Item { return Item{} }',
    'func Use(s Store) Item { return s.Get("a") }', ''].join('\n\n'));
  const m = mine(repo, '--lang', 'go').codemap;
  assert.deepEqual(m.classes.filter(k => k.bases?.length).map(k => `${short(k.id)} ${k.bases.map(short)}`), ['mem Store']);
  assert.deepEqual(edgesFrom(m, 'store.go:Use').map(e => `${short(e.to)} ${e.kind}`), ['Store.Get static', 'mem.Get virtual']);
  cleanup(dirname(repo));
});
